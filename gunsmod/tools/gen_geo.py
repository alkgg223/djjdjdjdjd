"""Export the vehicle geometry (armor.py / armor2.py) to Java: com.gunsmod.entity.VehicleGeo"""
import os

import armor as AR
import armor2 as A2
import armor3 as A3
import newveh_mesh as NV
import jet as J

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "java", "com", "gunsmod", "entity", "VehicleGeo.java")

TANK_FIELDS = ["turret", "gun", "muzzle", "seat", "coax", "trackX", "wheelsZ", "wheel", "idler", "sprocket", "bottom", "top",
               "front", "back", "exhaust", "smoke", "size"]


HELI_FIELDS = [("hub", "double[]"), ("rotorR", "double"), ("blades", "int"), ("hub2", "double"), ("tail", "double[]"), ("tailR", "double"),
               ("tailBlades", "int"), ("chin", "double[]"), ("chinLen", "double"), ("cannon", "double[]"), ("seats", "double[][]"),
               ("pods", "double[][]"), ("rails", "double[][]"), ("bombs", "double[][]"), ("flares", "double[][]"), ("ends", "double[][]"),
               ("pivotY", "double"), ("size", "double[]")]

CAR_FIELDS = [("turret", "double[]"), ("gun", "double[]"), ("muzzles", "double[][]"), ("tubes", "double[][]"), ("coax", "double[]"),
              ("radar", "double[]"), ("wheels", "double[][]"), ("wheelR", "double"), ("steerAxles", "int"), ("seats", "double[][]"),
              ("front", "double[][]"), ("back", "double[][]"), ("exhaust", "double[][]"), ("smoke", "double[]"), ("size", "double[]"),
              ("gunMin", "double"), ("gunMax", "double")]

JET_FIELDS = [("seat", "double[]"), ("cannon", "double[]"), ("nozzle", "double[]"), ("gearNose", "double[]"), ("gearMain", "double[]"),
              ("tips", "double[][]"), ("pylons", "double[][]"), ("flares", "double[][]"), ("ends", "double[][]"), ("pivotY", "double"),
              ("size", "double[]")]


def jt(v, t):
    """java literal of a value for a declared field type"""
    if v is None:
        return "0.0" if t == "double" else "0" if t == "int" else "null"
    if t == "int":
        return str(int(v))
    if t == "double":
        return repr(float(v))
    if t == "double[]":
        return "new double[]{" + ", ".join(repr(float(x)) for x in v) + "}"
    if t == "double[][]":
        return "new double[][]{" + ", ".join("{" + ", ".join(repr(float(x)) for x in r) + "}" for r in v) + "}"
    raise TypeError(t)


def jv(v):
    if isinstance(v, (int, float)):
        return repr(float(v))
    if isinstance(v, (list, tuple)) and v and isinstance(v[0], (list, tuple)):
        return "new double[][]{" + ", ".join("{" + ", ".join(repr(float(x)) for x in r) + "}" for r in v) + "}"
    if isinstance(v, (list, tuple)):
        return "new double[]{" + ", ".join(repr(float(x)) for x in v) + "}"
    if v is None:
        return "null"
    if isinstance(v, str):
        return '"' + v + '"'
    raise TypeError(v)


def abrams():
    return dict(turret=AR.TANK_TURRET_PIVOT, gun=AR.TANK_GUN_PIVOT[1:], muzzle=-14.85, seat=AR.TANK_SEAT, coax=(9.7, 7.2, 0.6),
                trackX=AR.TRACK_X, wheelsZ=AR.ROAD_WHEELS_Z, wheel=(AR.ROAD_WHEEL_Y, AR.ROAD_WHEEL_R), idler=AR.IDLER, sprocket=AR.SPROCKET,
                bottom=AR.TRACK_BOTTOM, top=AR.TRACK_TOP, front=[(1.6, 5.4, -5.8), (14.4, 5.4, -5.8), (8.0, 5.4, -6.2)],
                back=[(1.6, 5.4, 21.6), (14.4, 5.4, 21.6)], exhaust=[(5.0, 5.0, 21.8), (11.0, 5.0, 21.8)], smoke=(8, 6.2, 16), size=(4.2, 2.4))


def cobra():
    return dict(hub=AR.HELI_ROTOR_HUB, rotorR=18.4, blades=2, hub2=None, tail=AR.HELI_TAIL_HUB, tailR=2.6, tailBlades=2, chin=AR.HELI_CHIN,
                chinLen=2.4, cannon=None, seats=AR.HELI_SEATS, pods=AR.HELI_PODS, rails=[], bombs=[], flares=[(7.2, 3.8, 8.0), (8.8, 3.8, 8.0)],
                ends=[(8, 4, -12.6), (8, 7, 29.5)], pivotY=1.2, size=(3.4, 2.6))


def main():
    for fn in A2.TANKS.values():
        fn()
    tanks = {"abrams": ("tank", abrams())}
    for k in A2.TANKS:
        tanks[k] = (k, A2.GEO[k])
    lines = ["package com.gunsmod.entity;", "",
             "/** Generated by tools/gen_geo.py from the vehicle models: points in model units (0.25 block), front at -Z. */",
             "public final class VehicleGeo {", "    private VehicleGeo() {}", "",
             "    public record Tank(String model, " + ", ".join(("double " if f == "muzzle" else "double[][] " if f in ("front", "back", "exhaust") else "double[] ") + f for f in TANK_FIELDS) + ") {}", ""]
    for k, fn in NV.TANKS2.items():
        fn()
        tanks[k] = (k, NV.GEO[k])
    for name, (model, g) in tanks.items():
        args = [jv(model)] + [jv(g[f]) for f in TANK_FIELDS]
        lines.append(f"    public static final Tank {name.upper()} = new Tank({', '.join(args)});")
    for fn in A2.HELIS.values():
        fn()
    helis = {"cobra": ("heli", cobra())}
    for k in A2.HELIS:
        helis[k] = ("heli_" + k, A2.GEO[k])
    lines += ["", "    public record Heli(String model, " + ", ".join(t + " " + f for f, t in HELI_FIELDS) + ") {}", ""]
    for name, (model, g) in helis.items():
        args = [jv(model)] + [jt(g[f], t) for f, t in HELI_FIELDS]
        lines.append(f"    public static final Heli {name.upper()} = new Heli({', '.join(args)});")
    for fn in A3.CARS.values():
        fn()
    lines += ["", "    public record Car(String model, " + ", ".join(t + " " + f for f, t in CAR_FIELDS) + ") {}", ""]
    for fn in NV.CARS2.values():
        fn()
    for name in list(A3.CARS) + list(NV.CARS2):
        g = A3.GEO.get(name) or NV.GEO[name]
        args = [jv(name)] + [jt(g[f], t) for f, t in CAR_FIELDS]
        lines.append(f"    public static final Car {name.upper()} = new Car({', '.join(args)});")
    for fn in J.JETS.values():
        fn()
    lines += ["", "    /** jets: model units of 0.375 block */",
              "    public record Jet(String model, " + ", ".join(t + " " + f for f, t in JET_FIELDS) + ") {}", ""]
    for name in J.JETS:
        g = J.GEO[name]
        lines.append(f"    public static final Jet {name.upper()} = new Jet({', '.join([jv(name)] + [jt(g[f], t) for f, t in JET_FIELDS])});")
    lines += ["", "    /** TOW launcher on the Humvee turret (jeep units): elevation pivot and tube mouth */",
              f"    public static final double[] TOW_PIVOT = {jt(A3.TOW_PIVOT, 'double[]')};",
              f"    public static final double[] TOW_MUZZLE = {jt(A3.TOW_MUZZLE, 'double[]')};"]
    lines.append("}")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("geo ok", len(tanks))


if __name__ == "__main__":
    main()

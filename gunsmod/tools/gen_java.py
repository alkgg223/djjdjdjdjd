"""Writes client/GunGeometry.java from gun_meta.json (mount points, bounds and part lists of every gun model)."""
import json, os
meta = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "gun_meta.json")))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "java", "com", "gunsmod", "client", "GunGeometry.java")
order = ["m1911","p9","magnum50","revolver","smg5","micro_smg","vortex","pdw","ak47","m4a1","m16a4","br17","br77","tactical_rifle",
         "pump_shotgun","auto_shotgun","double_barrel","m24","svd","m107","m249","minigun","rpg7","m79","flamethrower"]
def v(p): return "new float[]{%sf, %sf, %sf}" % tuple(round(x, 4) for x in p)
lines = []
for g in order:
    m = meta[g]
    mo = m["mounts"]
    def get(k, d=(0, 0, 0)): return v(mo.get(k, d))
    parts = ", ".join('"%s"' % p for p in m["parts"])
    b = m["bounds"]
    lines.append(f'        put("{g}", new Geo({get("grip")}, {get("sight")}, {get("muzzle")}, {get("scope")}, {get("under")}, {get("side")}, '
                 f'{get("magdir", (0, -1, 0))}, {get("hinge")}, {get("spin")}, {get("pump")}, new float[]{{{", ".join(str(round(x, 3)) + "f" for x in b)}}}, new String[]{{{parts}}}));')
src = '''package com.gunsmod.client;

import java.util.HashMap;
import java.util.Map;

/** Generated by tools/gen_java.py from the gun models: mount points in model units (16 = 1 block). */
public final class GunGeometry {
    private GunGeometry() {}

    public record Geo(float[] grip, float[] sight, float[] muzzle, float[] scope, float[] under, float[] side, float[] magDir,
                      float[] hinge, float[] spin, float[] pump, float[] bounds, String[] parts) {
        public boolean has(String part) {
            for (String p : parts) if (p.equals(part)) return true;
            return false;
        }
    }

    private static final Map<String, Geo> MAP = new HashMap<>();

    private static void put(String id, Geo g) {
        MAP.put(id, g);
    }

    public static Geo get(String id) {
        return MAP.get(id);
    }

    static {
%s
    }
}
''' % "\n".join(lines)
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write(src)
print("wrote", out)

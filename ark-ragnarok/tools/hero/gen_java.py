"""Write SpeciesModels.java from tools/hero/meta/*.json (model scale, hitbox, eye height, seat) after an asset build."""
import json, os, glob, sys
HERE = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(HERE, "../../src/main/java/com/arkragnarok/species/SpeciesModels.java")
rows = []
for p in sorted(glob.glob(os.path.join(HERE, "meta", "*.json"))):
    m = json.load(open(p))
    seat = m["seat"] or [0.0, m["hip"]]
    rows.append('        M.put("%s", new Meta("%s", "%s", %sf, %sf, %sf, %sf, %sf, %sf, %sf, %sf, %s));' % (
        m["id"], m["name"], m["plan"], m["length_m"], m["scale"], m["width"], m["height"], m["eye"], m["hip"], seat[0], seat[1],
        "true" if m["saddle"] else "false"))
src = '''package com.arkragnarok.species;

import java.util.HashMap;
import java.util.Map;

/** GENERATED by tools/hero/gen_java.py from the asset build - model scale (1 m = 1 block), hitbox, eye height, saddle seat. */
public final class SpeciesModels {
    private SpeciesModels() {}

    public record Meta(String name, String plan, float length, float scale, float width, float height, float eye, float hip,
                       float seatForward, float seatHeight, boolean saddle) {}

    private static final Map<String, Meta> M = new HashMap<>();

    static {
%s
    }

    public static Meta get(String id) {
        Meta m = M.get(id);
        if (m == null) throw new IllegalStateException("no model data for " + id);
        return m;
    }
}
''' % "\n".join(rows)
open(out, "w").write(src)
print("wrote", len(rows), "species")

package com.arkragnarok.species;

/** how a wild creature reacts to players and other animals */
public enum Temper {
    /** hunts players and animals it can overpower */
    AGGRESSIVE,
    /** attacks anything that comes too close or hurts it */
    TERRITORIAL,
    /** only fights back */
    NEUTRAL,
    /** runs away from players and predators */
    SKITTISH
}
